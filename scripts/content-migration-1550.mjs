function linkRecall(text) {
  if (!text) return text;
  const protectedLinks = [];
  let out = text.replace(/@UUID\[Compendium\.sf2e\.actions\.Item\.1OagaWtBpVXExToo\]\{[^}]+\}/g, (m) => {
    const key = `\u0000RECALL${protectedLinks.length}\u0000`;
    protectedLinks.push(m);
    return key;
  });
  out = out.replace(/\b(?:Вспомнить\s+(?:сведения|информацию)|Вспомните\s+информацию|Вспомина(?:ть|ете)\s+информацию)\b/gi, RECALL);
  protectedLinks.forEach((m, i) => { out = out.replace(`\u0000RECALL${i}\u0000`, m); });
  return out;
}

function buildUpdate(item) {
  const source = item?._source ?? item?.toObject?.(false);
  if (!source) return null;
  const conv = source.flags?.[MODULE_ID]?.substanceConversion;
  const effectSource = source.flags?.[MODULE_ID]?.effectSourceItem;
  const update = {};
  if (conv?.version === "1.5.44" && SOURCE_NAMES[conv.source_name]) update.name = SOURCE_NAMES[conv.source_name];
  else if (OLD_NAMES[source.name]) update.name = OLD_NAMES[source.name];
  else if (OLD_EFFECT_NAMES[source.name]) update.name = OLD_EFFECT_NAMES[source.name];

  if (conv?.version === "1.5.44" || effectSource || NEW_BATCH_EFFECT_NAMES.has(source.name) || OLD_EFFECT_NAMES[source.name]) {
    const oldText = source.system?.description?.value ?? "";
    const newText = linkRecall(oldText);
    if (newText !== oldText) update["system.description.value"] = newText;
  }
  return Object.keys(update).length ? update : null;
}

async function migrateDocument(item) {
  const update = buildUpdate(item);
  if (!update) return false;
  await item.update(update, { render: false, [MODULE_ID]: { migration1550: true } });
  return true;
}

